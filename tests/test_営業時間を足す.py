# 2026-11-17 運用部・石川：ホテル日航金沢のスイートホリデーアフタヌーンティー。催しの言葉が無い期間限定の行で、
# 料金は「料金」の次の行の「・」の箇条書き。前の「」（ファウンテン）は会場
ページ2 = """
 スイートホリデーアフタヌーンティー
 期間
 ［開催中］ 2026年11月1日(日)〜12月25日(金)
 時間
 11:30～17:00(L.O.)
 料金
 ・1人 5,700円(税込)
 詳細・備考
"""


class 期間限定の行(unittest.TestCase):
    def test_期間のある行は催し(self):
        行 = "- 11/1(日)〜12/25(金)、ホテル日航金沢の「ファウンテン」で「スイートホリデーアフタヌーンティー」が登場（金沢日和の記事）"
        self.assertTrue(営業時間を足す._期間.search(行))
        self.assertEqual(営業時間を足す._主役の名.findall(行)[0], "スイートホリデーアフタヌーンティー")

    def test_箇条書きの料金をとる(self):
        v = 営業時間を足す.催しの欄(ページ2, "スイートホリデーアフタヌーンティー")
        self.assertIn("日時: 11:30～17:00(L.O.)", v)
        self.assertIn("料金: 1人 5,700円(税込)", v)

    def test_時刻も円も無い箇条書きは中身にしない(self):
        p = " 夏祭り\n 会場\n ・ステージ\n ・屋台\n"
        self.assertIsNone(営業時間を足す.催しの欄(p, "夏祭り"))


